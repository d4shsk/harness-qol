import { readFile, writeFile } from 'node:fs/promises';

const settings = await readFile(new URL('./settings-client.js', import.meta.url), 'utf8');
const images = await readFile(new URL('./images-client.js', import.meta.url), 'utf8');
const models = await readFile(new URL('./models-client.js', import.meta.url), 'utf8');
const btw = await readFile(new URL('./btw-client.js', import.meta.url), 'utf8');
const quote = await readFile(new URL('./quote-client.js', import.meta.url), 'utf8');
const workspaces = await readFile(new URL('./workspaces-client.js', import.meta.url), 'utf8');
const source = `// Generated by build.mjs from the feature modules.
window.__ModuleLoader__.load({
  id: '@local/harness-qol',
  factory(require) {
    const React = require('react');
${settings}
${images}
${models}
${btw}
${quote}
${workspaces}
    return {
      inject: ['slots', 'locale', 'sessions', 'remote'],
      apply(ctx) {
        const ns = 'harness-qol';
        const dictionaries = {
          en: {
            'image.menu': 'Image',
            'image.copy': 'Copy image',
            'image.copying': 'Copying…',
            'image.copied': 'Image copied',
            'image.copyFailed': 'Could not copy image.',
            'quote.action': 'Quote',
            'quote.copy': 'Copy',
            'quote.title': 'Quote from assistant',
            'quote.remove': 'Remove quote',
          },
          ru: {
            'image.menu': 'Изображение',
            'image.copy': 'Копировать изображение',
            'image.copying': 'Копирование…',
            'image.copied': 'Изображение скопировано',
            'image.copyFailed': 'Не удалось скопировать изображение.',
            'quote.action': 'Цитировать',
            'quote.copy': 'Копировать',
            'quote.title': 'Цитата из ответа',
            'quote.remove': 'Удалить цитату',
          },
        };
        for (const [language, dictionary] of Object.entries(dictionaries)) {
          ctx.effect(() => ctx.locale.register(ns, language, dictionary));
        }
        const t = ctx.locale.bind(ns);
        const store = qolModulesStore;
        store.sync();
        registerSettingsClient(ctx, React, t, store);
        ctx.effect(() => registerImageQol(ctx, React, t, store));
        ctx.effect(() => registerModelDefaultsClient(ctx, React, store));
        ctx.effect(() => registerBtwClient(ctx, React, store));
        ctx.effect(() => registerQuoteClient(ctx, React, t, store));
        ctx.inject(['uiWorkspace'], scope => scope.effect(() => registerWorkspacesClient(scope, React, store)));
        // Private settings requests are persisted for diagnostics but not shown as JSON chat cards.
        ctx.slots.inject('conversation.chat.commandview', () => ctx.slots.register({
          name: 'conversation.chat.commandview', key: 'harness-qol-models',
        }, () => null));
      },
    };
  },
});
`;
await writeFile(new URL('./client.js', import.meta.url), source);
console.log('Built Harness-QOL client.js');
